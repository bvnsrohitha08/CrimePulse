import React, { useState, useEffect } from 'react';
import { Link, useNavigate, useLocation } from 'react-router-dom';
import {
  AlertTriangle,
  Loader2,
  ChevronLeft,
  ChevronRight,
  RefreshCw,
  PlusCircle,
  FileQuestion,
  Eye,
} from 'lucide-react';
import { Card } from '../components/ui/Card';
import { Button } from '../components/ui/Button';
import { Badge } from '../components/ui/Badge';
import { useAuth } from '../hooks/useAuth';
import { getAnalysisHistory, ApiError } from '../services/apiService';
import { AnalysisDetailModal } from '../components/AnalysisDetailModal';

export function History() {
  const { logout } = useAuth();
  const navigate = useNavigate();
  const location = useLocation();

  // Data & Pagination state
  const [records, setRecords] = useState([]);
  const [pagination, setPagination] = useState({
    page: 1,
    limit: 10,
    total: 0,
    totalPages: 0,
  });

  // UI state
  const [isLoading, setIsLoading] = useState(true);
  const [error, setError] = useState(null);
  const [refreshTrigger, setRefreshTrigger] = useState(0);
  const [selectedAnalysisId, setSelectedAnalysisId] = useState(null);
  const [isModalOpen, setIsModalOpen] = useState(false);

  useEffect(() => {
    let isMounted = true;

    getAnalysisHistory({
      page: pagination.page,
      limit: 10,
    })
      .then((response) => {
        if (isMounted) {
          setRecords(response.records || []);
          if (response.pagination) {
            setPagination(response.pagination);
          }
          setError(null);
          setIsLoading(false);
        }
      })
      .catch((err) => {
        if (!isMounted) return;
        if (err instanceof ApiError && err.status === 401) {
          logout();
          navigate('/login', {
            state: {
              from: location,
              message: 'Your session has expired. Please sign in again to access history.',
            },
          });
          return;
        }
        setError(err.message || 'Failed to retrieve analysis history.');
        setIsLoading(false);
      });

    return () => {
      isMounted = false;
    };
  }, [pagination.page, refreshTrigger, logout, navigate, location]);

  const handlePageChange = (newPage) => {
    if (newPage < 1 || newPage > pagination.totalPages || isLoading) return;
    setPagination((prev) => ({ ...prev, page: newPage }));
  };

  const handleOpenDetail = (id) => {
    setSelectedAnalysisId(id);
    setIsModalOpen(true);
  };

  const handleCloseDetail = () => {
    setIsModalOpen(false);
    setSelectedAnalysisId(null);
  };

  const handleAuthErrorInModal = () => {
    setIsModalOpen(false);
    logout();
    navigate('/login', {
      state: {
        from: location,
        message: 'Your session has expired. Please sign in again.',
      },
    });
  };

  const formatDateTime = (isoString) => {
    if (!isoString) return '-';
    try {
      const d = new Date(isoString);
      if (isNaN(d.getTime())) return '-';
      return d.toLocaleString(undefined, {
        month: 'short',
        day: 'numeric',
        year: 'numeric',
        hour: '2-digit',
        minute: '2-digit',
      });
    } catch {
      return '-';
    }
  };

  const getStatusBadge = (status) => {
    switch (status) {
      case 'COMPLETED':
        return <Badge variant="success">COMPLETED</Badge>;
      case 'FAILED':
        return <Badge variant="danger">FAILED</Badge>;
      case 'PENDING':
        return <Badge variant="warning">PENDING</Badge>;
      default:
        return <Badge variant="default">{status || 'UNKNOWN'}</Badge>;
    }
  };

  return (
    <div className="space-y-6">
      {/* Page Header */}
      <div className="flex flex-col sm:flex-row sm:items-center sm:justify-between gap-4">
        <div>
          <div className="flex items-center gap-2 mb-1">
            <Badge variant="primary">Audit Records</Badge>
            <span className="text-xs text-slate-400">•</span>
            <span className="text-xs font-medium text-slate-500">Authenticated Session History</span>
          </div>
          <h1 className="text-2xl font-bold tracking-tight text-slate-900">
            Analysis Prediction History
          </h1>
          <p className="text-sm text-slate-500 mt-1 max-w-2xl leading-relaxed">
            Historical audit log of all crime pattern forecasts generated by your authenticated session,
            persisted in MongoDB Atlas.
          </p>
        </div>

        <div className="flex items-center gap-2">
          <Button
            variant="outline"
            size="sm"
            onClick={() => {
              setIsLoading(true);
              setRefreshTrigger((t) => t + 1);
            }}
            disabled={isLoading}
            className="text-xs"
            title="Refresh history records"
          >
            <RefreshCw className={`h-3.5 w-3.5 ${isLoading ? 'animate-spin' : ''}`} />
            <span>Refresh</span>
          </Button>

          <Link to="/predict">
            <Button variant="primary" size="sm" className="text-xs shadow-sm">
              <PlusCircle className="h-3.5 w-3.5" />
              <span>New Prediction</span>
            </Button>
          </Link>
        </div>
      </div>

      {/* Error Alert State */}
      {error && !isLoading && (
        <div
          role="alert"
          className="rounded-xl border border-rose-200 bg-rose-50 p-4 text-xs text-rose-800 space-y-2"
        >
          <div className="flex items-center gap-2 font-semibold text-rose-900">
            <AlertTriangle className="h-4 w-4 shrink-0 text-rose-600" />
            <span>Failed to Load History</span>
          </div>
          <p className="pl-6 leading-relaxed">{error}</p>
          <div className="pl-6 pt-1">
            <Button
              variant="outline"
              size="sm"
              onClick={() => {
                setIsLoading(true);
                setRefreshTrigger((t) => t + 1);
              }}
              className="text-xs border-rose-300 text-rose-900 hover:bg-rose-100"
            >
              Try Again
            </Button>
          </div>
        </div>
      )}

      {/* Loading State */}
      {isLoading && (
        <Card className="py-16 flex flex-col items-center justify-center space-y-3 text-slate-500">
          <Loader2 className="h-8 w-8 animate-spin text-brand-600" />
          <p className="text-sm font-medium">Retrieving saved analysis history from database...</p>
        </Card>
      )}

      {/* Empty State */}
      {!isLoading && !error && records.length === 0 && (
        <Card className="py-16 text-center space-y-4">
          <div className="mx-auto flex h-14 w-14 items-center justify-center rounded-full bg-slate-100 text-slate-400">
            <FileQuestion className="h-7 w-7" />
          </div>
          <div className="space-y-1 max-w-md mx-auto">
            <h3 className="text-lg font-bold text-slate-900">No Prediction Records Found</h3>
            <p className="text-xs text-slate-500 leading-relaxed">
              You haven&apos;t executed any crime pattern forecasts yet. Visit the Prediction Console
              to generate your first historical forecasting query.
            </p>
          </div>
          <div className="pt-2">
            <Link to="/predict">
              <Button variant="primary" size="md">
                <PlusCircle className="h-4 w-4" />
                <span>Go to Prediction Console</span>
              </Button>
            </Link>
          </div>
        </Card>
      )}

      {/* Records Table Card */}
      {!isLoading && !error && records.length > 0 && (
        <Card className="overflow-hidden p-0 shadow-sm border-slate-200">
          {/* Desktop & Tablet Table View */}
          <div className="hidden sm:block overflow-x-auto">
            <table className="w-full text-left text-xs">
              <thead className="bg-slate-50/90 border-b border-slate-200 text-slate-600 font-semibold uppercase tracking-wider text-[11px]">
                <tr>
                  <th className="py-3.5 px-4">ID</th>
                  <th className="py-3.5 px-4">Location</th>
                  <th className="py-3.5 px-4">Baseline / Target</th>
                  <th className="py-3.5 px-4">Predicted Category</th>
                  <th className="py-3.5 px-4">Confidence</th>
                  <th className="py-3.5 px-4">Status</th>
                  <th className="py-3.5 px-4">Timestamp</th>
                  <th className="py-3.5 px-4 text-right">Actions</th>
                </tr>
              </thead>
              <tbody className="divide-y divide-slate-100 text-slate-700">
                {records.map((item) => (
                  <tr
                    key={item._id}
                    className="hover:bg-slate-50/70 transition-colors cursor-pointer group"
                    onClick={() => handleOpenDetail(item._id)}
                  >
                    <td className="py-3.5 px-4 font-mono text-[11px] text-slate-500">
                      {item._id.slice(0, 8)}...{item._id.slice(-4)}
                    </td>
                    <td className="py-3.5 px-4 font-semibold text-slate-900">
                      {item.district}, {item.state}
                    </td>
                    <td className="py-3.5 px-4">
                      <span className="font-medium text-slate-800">{item.inputYear}</span>
                      <span className="text-slate-400 mx-1.5">→</span>
                      <span className="text-brand-700 font-semibold">
                        {item.targetYear ?? '-'}
                      </span>
                    </td>
                    <td className="py-3.5 px-4 font-bold text-slate-900">
                      {item.predictedCrime || (
                        <span className="text-slate-400 font-normal italic">
                          {item.status === 'FAILED' ? 'Failed' : 'Pending'}
                        </span>
                      )}
                    </td>
                    <td className="py-3.5 px-4 font-medium">
                      {typeof item.confidencePercentage === 'number' ? (
                        <span className="font-mono text-slate-800">
                          {item.confidencePercentage.toFixed(2)}%
                        </span>
                      ) : (
                        <span className="text-slate-400">-</span>
                      )}
                    </td>
                    <td className="py-3.5 px-4">{getStatusBadge(item.status)}</td>
                    <td className="py-3.5 px-4 text-slate-500 text-[11px]">
                      {formatDateTime(item.createdAt)}
                    </td>
                    <td className="py-3.5 px-4 text-right">
                      <Button
                        variant="outline"
                        size="sm"
                        onClick={(e) => {
                          e.stopPropagation();
                          handleOpenDetail(item._id);
                        }}
                        className="text-xs h-7 px-2.5 opacity-80 group-hover:opacity-100"
                        title="Inspect record"
                      >
                        <Eye className="h-3.5 w-3.5 text-brand-600" />
                        <span>Inspect</span>
                      </Button>
                    </td>
                  </tr>
                ))}
              </tbody>
            </table>
          </div>

          {/* Mobile Card List View */}
          <div className="sm:hidden divide-y divide-slate-100">
            {records.map((item) => (
              <div
                key={item._id}
                onClick={() => handleOpenDetail(item._id)}
                className="p-4 space-y-2.5 hover:bg-slate-50/70 transition-colors cursor-pointer"
              >
                <div className="flex items-start justify-between gap-2">
                  <div>
                    <div className="font-semibold text-slate-900 text-sm">
                      {item.district}, {item.state}
                    </div>
                    <div className="text-[11px] font-mono text-slate-400">
                      ID: {item._id.slice(0, 10)}...
                    </div>
                  </div>
                  {getStatusBadge(item.status)}
                </div>

                <div className="grid grid-cols-2 gap-2 text-xs pt-1">
                  <div>
                    <span className="text-slate-400 block text-[11px]">Predicted Crime</span>
                    <span className="font-bold text-slate-900">
                      {item.predictedCrime || '-'}
                    </span>
                  </div>
                  <div>
                    <span className="text-slate-400 block text-[11px]">Confidence</span>
                    <span className="font-semibold text-slate-800">
                      {typeof item.confidencePercentage === 'number'
                        ? `${item.confidencePercentage.toFixed(2)}%`
                        : '-'}
                    </span>
                  </div>
                  <div>
                    <span className="text-slate-400 block text-[11px]">Observation / Target</span>
                    <span className="font-medium text-slate-800">
                      {item.inputYear} → {item.targetYear ?? '-'}
                    </span>
                  </div>
                  <div>
                    <span className="text-slate-400 block text-[11px]">Date</span>
                    <span className="text-slate-600 text-[11px]">
                      {formatDateTime(item.createdAt)}
                    </span>
                  </div>
                </div>

                <div className="pt-2 flex justify-end">
                  <Button
                    variant="outline"
                    size="sm"
                    onClick={(e) => {
                      e.stopPropagation();
                      handleOpenDetail(item._id);
                    }}
                    className="text-xs h-7 w-full justify-center"
                  >
                    <Eye className="h-3.5 w-3.5 text-brand-600" />
                    <span>Inspect Record</span>
                  </Button>
                </div>
              </div>
            ))}
          </div>

          {/* Pagination Controls Footer */}
          <div className="flex flex-col sm:flex-row items-center justify-between px-4 py-3 border-t border-slate-100 text-xs text-slate-500 bg-slate-50/60 gap-3">
            <div>
              Showing{' '}
              <span className="font-semibold text-slate-700">
                {pagination.total === 0 ? 0 : (pagination.page - 1) * pagination.limit + 1}
              </span>{' '}
              to{' '}
              <span className="font-semibold text-slate-700">
                {Math.min(pagination.page * pagination.limit, pagination.total)}
              </span>{' '}
              of <span className="font-semibold text-slate-700">{pagination.total}</span> analyses
            </div>

            <div className="flex items-center gap-2">
              <Button
                variant="outline"
                size="sm"
                onClick={() => handlePageChange(pagination.page - 1)}
                disabled={pagination.page <= 1 || isLoading}
                className="text-xs h-8 px-2.5"
                aria-label="Previous page"
              >
                <ChevronLeft className="h-3.5 w-3.5" />
                <span>Previous</span>
              </Button>

              <span className="font-medium text-slate-700 px-2">
                Page {pagination.page} of {pagination.totalPages || 1}
              </span>

              <Button
                variant="outline"
                size="sm"
                onClick={() => handlePageChange(pagination.page + 1)}
                disabled={pagination.page >= pagination.totalPages || isLoading}
                className="text-xs h-8 px-2.5"
                aria-label="Next page"
              >
                <span>Next</span>
                <ChevronRight className="h-3.5 w-3.5" />
              </Button>
            </div>
          </div>
        </Card>
      )}

      {/* Analysis Detail Modal */}
      <AnalysisDetailModal
        isOpen={isModalOpen}
        onClose={handleCloseDetail}
        analysisId={selectedAnalysisId}
        onAuthError={handleAuthErrorInModal}
      />
    </div>
  );
}
